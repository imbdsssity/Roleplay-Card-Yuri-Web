import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { selectPublished } from '../src/lib/content-schema.mjs';

// Called by the build, never from a request. Records are validated by the shared contract.
export function makeAllowlist(items) {
  const entries = new Map();
  for (const item of selectPublished(items)) {
    for (const locale of ['en', 'zh']) {
      const variants = item.type === 'card'
        ? [[item.originalPng[locale], 'png'], [item.json[locale], 'json']]
        : [[item.json[locale], 'json']];
      for (const [file, kind] of variants) {
        if (!file?.sha256) throw new Error(`Missing checksum for published ${item.id}`);
        // Do not permit one object key to refer to different bytes, types, or filenames.
        const value = { key: file.objectKey, sha256: file.sha256, filename: file.filename, kind };
        const previous = entries.get(value.key);
        if (previous && JSON.stringify(previous) !== JSON.stringify(value)) {
          throw new Error(`Conflicting published object key: ${value.key}`);
        }
        entries.set(value.key, value);
      }
    }
  }
  return [...entries.values()].sort((a, b) => a.key.localeCompare(b.key, 'en'));
}

export async function buildAllowlist(root = process.cwd()) {
  const records = [];
  for (const directory of ['cards', 'worldbooks']) {
    const folder = join(root, 'src/content', directory);
    for (const name of (await readdir(folder)).sort()) {
      if (name.endsWith('.json')) records.push(JSON.parse(await readFile(join(folder, name), 'utf8')));
    }
  }
  const allowlist = makeAllowlist(records);
  const output = `// Generated by scripts/build-download-allowlist.mjs; do not edit.\nexport default ${JSON.stringify(allowlist, null, 2)};\n`;
  await writeFile(join(root, 'worker/.generated/published.mjs'), output);
  return allowlist.length;
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  console.log(`Built allowlist for ${await buildAllowlist()} published objects.`);
}
